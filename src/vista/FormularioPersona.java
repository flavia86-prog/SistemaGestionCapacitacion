    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {                                           
        try {
    int dni = Integer.parseInt(txtDni.getText());

    modelo.Persona persona = new modelo.Persona(
            dni,
            txtApellido.getText(),
            txtNombre.getText(),
            txtJerarquia.getText()
    );

    dao.PersonaDAO dao = new dao.PersonaDAO();

    if (dao.existeDocumento(dni)) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "La persona ya está registrada."
        );
    } else {
        dao.insertar(persona);

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Persona registrada correctamente."
        );

        txtDni.setText("");
        txtApellido.setText("");
        txtNombre.setText("");
        txtJerarquia.setText("");
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "El DNI debe contener solamente números."
    );

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }                                          

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {                                          
try {
    int dni = Integer.parseInt(txtDni.getText());

    PersonaDAO dao = new PersonaDAO();
    Persona persona = dao.buscarPorDocumento(dni);

    if (persona != null) {
        txtApellido.setText(persona.getApellido());
        txtNombre.setText(persona.getNombre());
        txtJerarquia.setText(persona.getJerarquia());

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Persona encontrada."
        );

    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se encontró una persona con ese DNI."
        );
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Ingrese un DNI válido."
    );

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error al consultar la base de datos: " + e.getMessage()
    );

} catch (ExcepcionNegocio e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage()
    );
}
    }                                         

